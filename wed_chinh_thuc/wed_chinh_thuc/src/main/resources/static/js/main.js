/* ==================================================
   1. TÌM KIẾM SẢN PHẨM
   ==================================================

   Cần code:

   - Lấy nội dung từ #searchInput
   - Khi người dùng nhấn #searchButton
   - Tìm sản phẩm có tên phù hợp
   - Hiển thị những sản phẩm phù hợp
   - Nếu không tìm thấy sản phẩm thì thông báo

*/


/* ==================================================
   2. LỌC SẢN PHẨM
   ==================================================

   Cần code:

   - Lọc theo loại kính:
       + Kính cận
       + Kính râm
       + Kính thời trang
       + Kính chống ánh sáng xanh

   - Lọc theo khoảng giá
   - Hiển thị sản phẩm sau khi lọc

*/


/* ==================================================
   3. SẮP XẾP SẢN PHẨM
   ==================================================

   Cần code:

   - Sắp xếp giá thấp -> cao
   - Sắp xếp giá cao -> thấp
   - Có thể thêm:
       + Mới nhất
       + Bán chạy

*/


/* ==================================================
   4. THÊM SẢN PHẨM VÀO GIỎ HÀNG
   ==================================================

   Cần code:

   - Bắt sự kiện click của .addToCartButton
   - Lấy thông tin sản phẩm
   - Thêm sản phẩm vào giỏ hàng
   - Nếu sản phẩm đã tồn tại thì tăng số lượng
   - Cập nhật số lượng trên biểu tượng giỏ hàng

*/


/* ==================================================
   5. LOCAL STORAGE
   ==================================================

   Cần code:

   - Lưu giỏ hàng vào localStorage
   - Đọc giỏ hàng từ localStorage
   - Giữ giỏ hàng khi người dùng reload trang
   - Xóa giỏ hàng khi cần

*/


/* ==================================================
   6. TRANG CHI TIẾT SẢN PHẨM
   ==================================================

   Cần code:

   - Khi click vào sản phẩm
   - Lấy ID sản phẩm
   - Hiển thị:
       + Tên sản phẩm
       + Hình ảnh
       + Giá
       + Mô tả
       + Loại kính
       + Số lượng

*/


/* ==================================================
   7. GIỎ HÀNG
   ==================================================

   Cần code:

   - Hiển thị các sản phẩm trong giỏ
   - Tăng số lượng
   - Giảm số lượng
   - Xóa sản phẩm
   - Tính thành tiền từng sản phẩm
   - Tính tổng tiền đơn hàng

*/


/* ==================================================
   8. THANH TOÁN
   ==================================================

   Cần code:

   - Lấy thông tin từ form:
       + Họ tên
       + Số điện thoại
       + Email
       + Địa chỉ
       + Phương thức thanh toán

   - Kiểm tra dữ liệu nhập vào
   - Không cho gửi nếu dữ liệu không hợp lệ
   - Hiển thị thông báo đặt hàng thành công

*/


/* ==================================================
   9. VALIDATE FORM
   ==================================================

   Cần code:

   - Kiểm tra họ tên không được bỏ trống
   - Kiểm tra số điện thoại
   - Kiểm tra email
   - Kiểm tra địa chỉ
   - Hiển thị thông báo lỗi

*/


/* ==================================================
   10. MENU / RESPONSIVE
   ==================================================

   Nếu sau này cần:

   - Menu mobile
   - Nút mở / đóng menu
   - Xử lý giao diện trên điện thoại

*/


/* ==================================================
   11. THÔNG BÁO
   ==================================================

   Có thể code:

   - "Đã thêm sản phẩm vào giỏ hàng"
   - "Đã xóa sản phẩm"
   - "Đặt hàng thành công"
   - "Không tìm thấy sản phẩm"

*/


/* ==================================================
   12. CẬP NHẬT SỐ LƯỢNG GIỎ HÀNG
   ==================================================

   Ví dụ:

   🛒 Giỏ hàng (3)

   Cần cập nhật số 3 theo số lượng sản phẩm
   hiện đang có trong giỏ hàng.

*/
